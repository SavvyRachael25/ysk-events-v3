#!/usr/bin/env node
/**
 * Builds the encrypted funding board served at /funding.
 *
 * The board's content is private, and this repository is public, so only an
 * encrypted copy is committed (lib/funding-board.enc.ts). The server decrypts
 * it with FUNDING_DATA_KEY, and only after the visitor has entered the
 * password (FUNDING_PASSWORD). Both live in Vercel's environment variables,
 * never in git.
 *
 * Inputs, kept out of git in .funding-src/ (see .gitignore):
 *   .funding-src/board.html         the board page as published on claude.ai
 *   .funding-src/db/<collection>/<doc_id>.json
 *                                   a snapshot of the board's shared data
 *   .funding-src/key                FUNDING_DATA_KEY (base64, 32 bytes);
 *                                   or set FUNDING_DATA_KEY in the shell
 *
 * Run:  node scripts/funding/build.mjs
 * Then commit lib/funding-board.enc.ts and deploy.
 */

import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { createCipheriv, randomBytes } from "node:crypto";

const SRC = ".funding-src";
const OUT = "lib/funding-board.enc.ts";

const keyB64 =
  process.env.FUNDING_DATA_KEY ||
  (existsSync(join(SRC, "key")) ? readFileSync(join(SRC, "key"), "utf8").trim() : "");
const key = Buffer.from(keyB64, "base64");
if (key.length !== 32) {
  console.error("FUNDING_DATA_KEY must be 32 bytes, base64 encoded.");
  process.exit(1);
}

// Snapshot of the shared data, shaped as { collection: [{ id, data }] }.
const dbDir = join(SRC, "db");
const data = {};
for (const coll of readdirSync(dbDir)) {
  const dir = join(dbDir, coll);
  if (!statSync(dir).isDirectory()) continue;
  data[coll] = readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .sort()
    .map((f) => ({ id: f.replace(/\.json$/, ""), data: JSON.parse(readFileSync(join(dir, f), "utf8")) }));
}

const snapshotDate = process.env.FUNDING_SNAPSHOT_DATE || new Date().toISOString().slice(0, 10);

// The board was written for claude.ai, where window.claude supplies the
// shared database. This stand-in serves the snapshot instead, read only.
const shim = `<meta name="robots" content="noindex,nofollow">
<script>
(function(){
  var DATA=${JSON.stringify(data).replace(/</g, "\\u003c")};
  var SNAP=${JSON.stringify(snapshotDate)};
  function no(){ return Promise.reject({code:"read-only"}); }
  function docSnap(id,body){ return {id:id,exists:!!body,data:function(){ return body?JSON.parse(JSON.stringify(body)):undefined; }}; }
  function later(fn){ setTimeout(fn,0); return function(){}; }
  var db={
    collection:function(name){
      return {
        onSnapshot:function(cb){ return later(function(){ cb({docs:(DATA[name]||[]).map(function(r){ return docSnap(r.id,r.data); })}); }); },
        add:no,
        doc:function(){ return {set:no,update:no,delete:no}; }
      };
    },
    doc:function(path){
      var p=String(path).split("/"), coll=p[0], id=p[1], hit=null;
      (DATA[coll]||[]).forEach(function(r){ if(r.id===id) hit=r.data; });
      return {
        onSnapshot:function(cb){ return later(function(){ cb(docSnap(id,hit)); }); },
        get:function(){ return Promise.resolve(docSnap(id,hit)); },
        set:no, update:no, delete:no
      };
    }
  };
  function note(){
    var el=document.getElementById("footStatus");
    if(el) el.textContent="Read-only copy of the funding board, last updated "+SNAP+". Ask Rachael for changes.";
  }
  window.claude={use:function(name){
    if(name==="db") return Promise.resolve(db);
    if(name==="user") return Promise.resolve({can:function(){ setTimeout(note,0); return false; }});
    return Promise.resolve(null);
  }};
})();
</script>
`;

let html = readFileSync(join(SRC, "board.html"), "utf8");
if (!html.includes("<body>")) {
  console.error("board.html has no <body> tag; is it the full page?");
  process.exit(1);
}
html = html.replace("<body>", "<body>\n" + shim);

const iv = randomBytes(12);
const cipher = createCipheriv("aes-256-gcm", key, iv);
const ct = Buffer.concat([cipher.update(html, "utf8"), cipher.final()]);
const tag = cipher.getAuthTag();

const out = `// Generated by scripts/funding/build.mjs. Do not edit by hand.
// AES-256-GCM ciphertext of the funding board page. Unreadable without
// FUNDING_DATA_KEY, which lives only in Vercel's environment variables.
export const FUNDING_BOARD_ENC = {
  snapshot: ${JSON.stringify(snapshotDate)},
  iv: ${JSON.stringify(iv.toString("base64"))},
  tag: ${JSON.stringify(tag.toString("base64"))},
  ct: ${JSON.stringify(ct.toString("base64"))},
};
`;
writeFileSync(OUT, out);
const counts = Object.entries(data).map(([k, v]) => `${k}:${v.length}`).join(" ");
console.log(`Wrote ${OUT} (${out.length} bytes). Snapshot ${snapshotDate}. ${counts}`);
